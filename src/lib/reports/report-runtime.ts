export type RuntimeParameterValue = string | boolean;
export type RuntimeParameterValues = Record<string, RuntimeParameterValue>;

/**
 * Contact data of a quotation (Backend `services/reports/quotation_contact.py`):
 * optional texts the backend trims and bounds. A blank folio is generated by
 * the backend and comes back in the execution's `parameters`, so the preview
 * shows it; the form never invents one.
 */
export const QUOTATION_CONTACT_PARAMETERS = ["cliente", "atencion", "folio"] as const;
export const QUOTATION_FOLIO_PARAMETER = "folio";
export const QUOTATION_CONTACT_MAX_LENGTH = 200;
export const QUOTATION_FOLIO_HINT = "Si lo dejas vacío, el sistema genera un folio automáticamente.";

export function isQuotationContactParameter(parameter: ReportParameter): boolean {
  return parameter.data_type === "string"
    && parameter.input_type === "text"
    && (QUOTATION_CONTACT_PARAMETERS as readonly string[]).includes(parameter.name);
}

/** The helper text shown under a parameter's input, if it has one. */
export function runtimeParameterHint(parameter: ReportParameter): string | null {
  return isQuotationContactParameter(parameter) && parameter.name === QUOTATION_FOLIO_PARAMETER
    ? QUOTATION_FOLIO_HINT
    : null;
}

/**
 * Origin of a quotation line (Backend `services/reports/repeatable.py`). A
 * LIST_PRODUCT line is a product of the selected price list, priced by it; a
 * MANUAL_PRODUCT line is captured by hand and exists only in the execution.
 */
export const LIST_PRODUCT = "LIST_PRODUCT";
export const MANUAL_PRODUCT = "MANUAL_PRODUCT";
export type RuntimeLineOrigin = typeof LIST_PRODUCT | typeof MANUAL_PRODUCT;

/** Reserved row keys a manual line sends instead of the product. */
export const MANUAL_LINE_FIELDS = ["part_number", "description", "unit_of_measure", "unit_price"] as const;
export type ManualLineField = (typeof MANUAL_LINE_FIELDS)[number];
const MANUAL_TEXT_LIMITS: Record<Exclude<ManualLineField, "unit_price">, number> = {
  part_number: 100,
  description: 500,
  unit_of_measure: 30,
};
/** Mirrors the backend bound; prices are exact decimals with at most two places. */
const MAX_MANUAL_UNIT_PRICE = 9_999_999_999.99;
const MANUAL_PRICE = /^\d+(?:\.\d{1,2})?$/;
const CONTROL_CHARACTERS = /[\u0000-\u001f\u007f]/;

export interface RuntimeGroupRow {
  id: string;
  values: RuntimeParameterValues;
  /** Only rows of a group with `allow_manual_items`; absent means a list product. */
  origin?: RuntimeLineOrigin;
}

export function isManualRow(group: ReportParameterGroup, row: RuntimeGroupRow): boolean {
  return group.allow_manual_items === true && row.origin === MANUAL_PRODUCT;
}

export type RuntimeGroupValues = Record<string, RuntimeGroupRow[]>;

export interface RuntimeParameterValidation {
  fieldErrors: Record<string, string>;
  formError: string | null;
  parameters: Record<string, unknown>;
  valid: boolean;
}

export interface RuntimeFormValidation extends RuntimeParameterValidation {
  groupErrors: Record<string, string>;
  rowErrors: Record<string, Record<number, Record<string, string>>>;
}

/** A required field that is still empty: pending, not wrong. */
export const REQUIRED_FIELD_MESSAGE = "Este campo es requerido.";

/** What the user has done to the form so far (Frontend #42, D9). */
export interface RuntimeInteraction {
  /** Scalar parameters the user changed. */
  fields: ReadonlySet<string>;
  /** Row cells the user changed, as `runtimeCellKey(group, row.id, field)`. */
  cells: ReadonlySet<string>;
  /** The user pressed «Generar» while the form was incomplete or invalid. */
  attempted: boolean;
}

export function runtimeCellKey(groupName: string, rowId: string, fieldName: string): string {
  return `${groupName}:${rowId}:${fieldName}`;
}

/**
 * Validation stays complete — it still decides whether anything is sent —
 * but a required field that is merely empty is not shown as an error until
 * the user has touched it or tried to generate. Wrong values (a non-integer
 * quantity, a discount over 100) are always shown.
 */
export function visibleRuntimeErrors(
  validation: RuntimeFormValidation,
  groupValues: RuntimeGroupValues,
  interaction: RuntimeInteraction,
): Pick<RuntimeFormValidation, "fieldErrors" | "rowErrors"> {
  const shown = (message: string, touched: boolean) =>
    interaction.attempted || touched || message !== REQUIRED_FIELD_MESSAGE;
  const fieldErrors = Object.fromEntries(
    Object.entries(validation.fieldErrors).filter(([name, message]) => shown(message, interaction.fields.has(name))),
  );
  const rowErrors: RuntimeFormValidation["rowErrors"] = {};
  for (const [groupName, rows] of Object.entries(validation.rowErrors)) {
    for (const [index, fields] of Object.entries(rows)) {
      const rowId = groupValues[groupName]?.[Number(index)]?.id ?? "";
      for (const [fieldName, message] of Object.entries(fields)) {
        if (!shown(message, interaction.cells.has(runtimeCellKey(groupName, rowId, fieldName)))) continue;
        rowErrors[groupName] ??= {};
        rowErrors[groupName][Number(index)] ??= {};
        rowErrors[groupName][Number(index)][fieldName] = message;
      }
    }
  }
  return { fieldErrors, rowErrors };
}

/** Row cells whose value differs between two versions of the form. */
export function changedRuntimeCells(previous: RuntimeGroupValues, next: RuntimeGroupValues): string[] {
  const changed: string[] = [];
  for (const [groupName, rows] of Object.entries(next)) {
    const before = new Map((previous[groupName] ?? []).map((row) => [row.id, row.values]));
    for (const row of rows) {
      const old = before.get(row.id);
      if (old == null) continue; // a new, untouched row
      for (const [fieldName, value] of Object.entries(row.values)) {
        if (old[fieldName] !== value) changed.push(runtimeCellKey(groupName, row.id, fieldName));
      }
    }
  }
  return changed;
}

export function orderedReportParameters(parameters: ReportParameter[]): ReportParameter[] {
  return parameters
    .map((parameter, index) => ({ parameter, index }))
    .sort((left, right) =>
      left.parameter.display_order - right.parameter.display_order || left.index - right.index,
    )
    .map(({ parameter }) => parameter);
}

export function orderedParameterGroups(groups: ReportParameterGroup[]): ReportParameterGroup[] {
  return stableDisplayOrder(groups);
}

export function orderedGroupFields(fields: ReportParameterGroupField[]): ReportParameterGroupField[] {
  return stableDisplayOrder(fields);
}

function stableDisplayOrder<T extends { display_order: number }>(values: T[]): T[] {
  return values
    .map((value, index) => ({ value, index }))
    .sort((left, right) => left.value.display_order - right.value.display_order || left.index - right.index)
    .map(({ value }) => value);
}

function initialValue(parameter: ReportParameter | ReportParameterGroupField): RuntimeParameterValue {
  const value = parameter.default_value;
  if (parameter.data_type === "boolean" || parameter.input_type === "checkbox") {
    if (typeof value === "boolean") return value;
    return value === "true" || value === "1" || value === 1;
  }
  if (value == null) return "";
  const serialized = String(value);
  if (parameter.input_type === "datetime") return serialized.slice(0, 16);
  if (parameter.input_type === "date") return serialized.slice(0, 10);
  return serialized;
}

export function initialRuntimeValues(
  parameters: ReportParameter[],
  overrides: Record<string, unknown> = {},
): RuntimeParameterValues {
  return Object.fromEntries(parameters.map((parameter) => {
    const override = overrides[parameter.name];
    if (override == null) return [parameter.name, initialValue(parameter)];
    if (parameter.data_type === "boolean" || parameter.input_type === "checkbox") {
      return [parameter.name, typeof override === "boolean" ? override : override === "true" || override === "1"];
    }
    return [parameter.name, String(override)];
  }));
}

export function initialRuntimeGroupValues(groups: ReportParameterGroup[]): RuntimeGroupValues {
  return Object.fromEntries(orderedParameterGroups(groups).map((group) => [
    group.name,
    Array.from({ length: group.min_items }, (_, index) => createRuntimeGroupRow(group, `${group.name}-${index}`)),
  ]));
}

export function createRuntimeGroupRow(
  group: ReportParameterGroup,
  id: string,
  origin: RuntimeLineOrigin = LIST_PRODUCT,
): RuntimeGroupRow {
  const values = Object.fromEntries(orderedGroupFields(group.fields).map((field) => [field.name, initialValue(field)]));
  if (!group.allow_manual_items) return { id, values };
  if (origin === MANUAL_PRODUCT) {
    for (const field of MANUAL_LINE_FIELDS) values[field] = "";
  }
  return { id, values, origin };
}

function validateManualField(field: ManualLineField, raw: RuntimeParameterValue | undefined): string | null {
  const text = typeof raw === "string" ? raw.trim() : "";
  if (field === "unit_price") {
    if (text === "") return REQUIRED_FIELD_MESSAGE;
    if (!MANUAL_PRICE.test(text)) return "Captura un precio no negativo con hasta dos decimales.";
    if (Number(text) > MAX_MANUAL_UNIT_PRICE) return "El precio es demasiado grande.";
    return null;
  }
  if (text === "") return field === "description" ? REQUIRED_FIELD_MESSAGE : null;
  if (CONTROL_CHARACTERS.test(text)) return "No admite saltos de línea.";
  const limit = MANUAL_TEXT_LIMITS[field];
  return text.length > limit ? `Máximo ${limit} caracteres.` : null;
}

function isValidDate(value: string): boolean {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (match == null) return false;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const candidate = new Date(Date.UTC(year, month - 1, day));
  return candidate.getUTCFullYear() === year && candidate.getUTCMonth() === month - 1 && candidate.getUTCDate() === day;
}

function isValidDateTime(value: string): boolean {
  const match = /^(\d{4}-\d{2}-\d{2})T([01]\d|2[0-3]):([0-5]\d)(?::([0-5]\d)(?:\.\d+)?)?$/.exec(value);
  return match != null && isValidDate(match[1]);
}

function coerceValue(parameter: ReportParameter | ReportParameterGroupField, raw: RuntimeParameterValue): unknown {
  if (typeof raw === "boolean") return raw;
  if (raw === "") return undefined;
  if (parameter.data_type === "integer") return Number(raw);
  if (parameter.data_type === "boolean") return raw === "true" || raw === "1";
  // Decimal strings intentionally remain strings. FastAPI/Pydantic performs
  // the authoritative coercion without a browser floating-point round trip.
  return raw;
}

function numericConstraint(configuration: ReportNumericConfiguration, key: "minimum" | "maximum"): number | null {
  const raw = configuration[key];
  if (raw == null || raw === "") return null;
  const value = Number(raw);
  return Number.isFinite(value) ? value : null;
}

function validateGroupField(field: ReportParameterGroupField, raw: RuntimeParameterValue): string | null {
  const empty = typeof raw === "string" && raw.trim() === "";
  if (field.required && empty) return REQUIRED_FIELD_MESSAGE;
  if (empty) return null;

  if (typeof raw === "string" && field.input_type === "number") {
    const numeric = Number(raw);
    if (!Number.isFinite(numeric) || (field.data_type === "integer" && !Number.isInteger(numeric))) {
      return field.data_type === "integer" ? "Captura un número entero válido." : "Captura un número válido.";
    }
    const configuration = field.configuration_json ?? {};
    if (!("options_source" in configuration)) {
      const minimum = numericConstraint(configuration, "minimum");
      const maximum = numericConstraint(configuration, "maximum");
      if (minimum != null && (configuration.exclusive_minimum ? numeric <= minimum : numeric < minimum)) {
        return configuration.exclusive_minimum
          ? `Debe ser mayor que ${minimum}.`
          : `Debe ser mayor o igual que ${minimum}.`;
      }
      if (maximum != null && (configuration.exclusive_maximum ? numeric >= maximum : numeric > maximum)) {
        return configuration.exclusive_maximum
          ? `Debe ser menor que ${maximum}.`
          : `Debe ser menor o igual que ${maximum}.`;
      }
    }
  }
  if (typeof raw === "string" && field.input_type === "date" && !isValidDate(raw)) {
    return "Captura una fecha válida.";
  }
  if (typeof raw === "string" && field.input_type === "datetime" && !isValidDateTime(raw)) {
    return "Captura una fecha y hora válidas.";
  }
  return null;
}

export function validateRuntimeParameters(
  code: string,
  parameters: ReportParameter[],
  values: RuntimeParameterValues,
): RuntimeParameterValidation {
  const fieldErrors: Record<string, string> = {};
  const payload: Record<string, unknown> = {};

  for (const parameter of orderedReportParameters(parameters)) {
    const raw = values[parameter.name] ?? (parameter.input_type === "checkbox" ? false : "");
    const empty = typeof raw === "string" && raw.trim() === "";
    if (parameter.required && empty) {
      fieldErrors[parameter.name] = REQUIRED_FIELD_MESSAGE;
      continue;
    }
    if (empty) continue;

    if (typeof raw === "string" && parameter.input_type === "number") {
      const numeric = Number(raw);
      if (!Number.isFinite(numeric) || (parameter.data_type === "integer" && !Number.isInteger(numeric))) {
        fieldErrors[parameter.name] = parameter.data_type === "integer"
          ? "Captura un número entero válido."
          : "Captura un número válido.";
        continue;
      }
    }
    if (typeof raw === "string" && parameter.input_type === "date" && !isValidDate(raw)) {
      fieldErrors[parameter.name] = "Captura una fecha válida.";
      continue;
    }
    if (typeof raw === "string" && parameter.input_type === "datetime" && !isValidDateTime(raw)) {
      fieldErrors[parameter.name] = "Captura una fecha y hora válidas.";
      continue;
    }

    payload[parameter.name] = coerceValue(parameter, raw);
  }

  let formError: string | null = null;
  if (
    code === PRICE_LIST_COMPARISON_CODE &&
    payload.price_list_a_id != null &&
    payload.price_list_a_id === payload.price_list_b_id
  ) {
    formError = "Selecciona dos listas distintas.";
  }

  return {
    fieldErrors,
    formError,
    parameters: payload,
    valid: Object.keys(fieldErrors).length === 0 && formError == null,
  };
}

export function validateRuntimeForm(
  code: string,
  parameters: ReportParameter[],
  groups: ReportParameterGroup[],
  values: RuntimeParameterValues,
  groupValues: RuntimeGroupValues,
): RuntimeFormValidation {
  const scalar = validateRuntimeParameters(code, parameters, values);
  const payload = { ...scalar.parameters };
  const groupErrors: Record<string, string> = {};
  const rowErrors: Record<string, Record<number, Record<string, string>>> = {};

  for (const group of orderedParameterGroups(groups)) {
    const rows = groupValues[group.name] ?? [];
    if (rows.length < group.min_items) {
      groupErrors[group.name] = `Agrega al menos ${group.min_items} ${group.min_items === 1 ? "renglón" : "renglones"}.`;
    } else if (group.max_items != null && rows.length > group.max_items) {
      groupErrors[group.name] = `El grupo permite como máximo ${group.max_items} renglones.`;
    }

    const product = productSearchField(group);
    payload[group.name] = rows.map((row, rowIndex) => {
      const serialized: Record<string, unknown> = {};
      const manual = isManualRow(group, row);
      const fail = (fieldName: string, error: string) => {
        rowErrors[group.name] ??= {};
        rowErrors[group.name][rowIndex] ??= {};
        rowErrors[group.name][rowIndex][fieldName] = error;
      };
      if (group.allow_manual_items) serialized.origin = manual ? MANUAL_PRODUCT : LIST_PRODUCT;
      for (const field of orderedGroupFields(group.fields)) {
        // A manual line is never linked to a catalog product.
        if (manual && field.name === product?.name) continue;
        const raw = row.values[field.name] ?? (field.input_type === "checkbox" ? false : "");
        const error = validateGroupField(field, raw);
        if (error) {
          fail(field.name, error);
          continue;
        }
        const empty = typeof raw === "string" && raw.trim() === "";
        if (!empty) serialized[field.name] = coerceValue(field, raw);
      }
      if (manual) {
        for (const field of MANUAL_LINE_FIELDS) {
          const raw = row.values[field];
          const error = validateManualField(field, raw);
          if (error) {
            fail(field, error);
            continue;
          }
          // Prices stay exact decimal strings; optional blanks are omitted.
          const text = typeof raw === "string" ? raw.trim() : "";
          if (text !== "") serialized[field] = text;
        }
      }
      return serialized;
    });
  }

  return {
    fieldErrors: scalar.fieldErrors,
    formError: scalar.formError,
    groupErrors,
    rowErrors,
    parameters: payload,
    valid: scalar.valid && Object.keys(groupErrors).length === 0 && Object.keys(rowErrors).length === 0,
  };
}

/**
 * Line-item conventions of the quotation data source (Backend #20). The field
 * *names* are part of that contract, so the table can price a line locally.
 */
/** The field a group resolves through the product search, if it has one. */
export function productSearchField(group: ReportParameterGroup): ReportParameterGroupField | null {
  return orderedGroupFields(group.fields).find((field) => {
    const configuration = field.configuration_json;
    return configuration != null
      && "options_source" in configuration
      && configuration.options_source === "products_by_price_list";
  }) ?? null;
}

/**
 * Human labels for the option-backed parameters of one execution (Frontend
 * #45): `price_list_id = 1` reads "DONALDSON · 2026-10-01 · USD". Built from
 * the options the runtime already loaded and the exact values sent, so a
 * regenerated report never shows a stale label; the payload keeps raw values.
 */
export function parameterDisplayValues(
  parameters: ReportParameter[],
  sent: Record<string, unknown>,
  options: Record<string, ReportOption[]>,
): Record<string, string> {
  const labels: Record<string, string> = {};
  for (const parameter of parameters) {
    if (parameter.input_type !== "select") continue;
    const value = sent[parameter.name];
    if (value == null || value === "") continue;
    const option = (options[parameter.name] ?? []).find((candidate) => String(candidate.value) === String(value));
    if (option) labels[parameter.name] = option.label;
  }
  return labels;
}

/**
 * Currency of the price list an execution was generated with, from the
 * option the runtime loaded for the exact value sent; `null` when the report
 * has no price list or the backend does not say (older versions).
 */
export function parameterCurrency(
  parameters: ReportParameter[],
  sent: Record<string, unknown>,
  options: Record<string, ReportOption[]>,
): string | null {
  for (const parameter of parameters) {
    const configuration = parameter.configuration_json as { options_source?: unknown } | null;
    if (parameter.input_type !== "select" || configuration?.options_source !== "price_lists") continue;
    const value = sent[parameter.name];
    if (value == null || value === "") continue;
    const option = (options[parameter.name] ?? []).find((candidate) => String(candidate.value) === String(value));
    if (typeof option?.currency === "string" && option.currency !== "") return option.currency;
  }
  return null;
}

export function backendRowErrors(
  detail: unknown,
  groups: ReportParameterGroup[],
): Record<string, Record<number, Record<string, string>>> {
  const groupNames = new Set(groups.map((group) => group.name));
  const errors: Record<string, Record<number, Record<string, string>>> = {};
  if (!Array.isArray(detail)) return errors;
  for (const item of detail) {
    if (!item || typeof item !== "object") continue;
    const { loc, msg, message } = item as { loc?: unknown[]; msg?: unknown; message?: unknown };
    const normalized = loc?.[0] === "body" ? loc.slice(1) : loc;
    const group = normalized?.[0];
    const row = normalized?.[1];
    const field = normalized?.[2];
    const text = typeof msg === "string" ? msg : typeof message === "string" ? message : null;
    if (typeof group !== "string" || !groupNames.has(group) || typeof row !== "number" || typeof field !== "string" || !text) continue;
    errors[group] ??= {};
    errors[group][row] ??= {};
    errors[group][row][field] = text;
  }
  return errors;
}

export function isReportBuilderPreviewResponse(value: unknown): value is ReportBuilderPreviewResponse {
  if (!value || typeof value !== "object") return false;
  const candidate = value as Partial<ReportBuilderPreviewResponse>;
  return Array.isArray(candidate.columns)
    && candidate.columns.every((column) => column && typeof column === "object" && "key" in column && "label" in column)
    && Array.isArray(candidate.rows)
    && candidate.totals != null
    && typeof candidate.totals === "object"
    && typeof candidate.row_count === "number"
    && typeof candidate.truncated === "boolean";
}

/**
 * Public id of the immutable snapshot the backend persisted for this dataset
 * (Backend #25). Builder datasets and modern dedicated runtimes carry one;
 * legacy payloads answer `null`.
 */
export function reportExecutionId(payload: unknown): string | null {
  if (!isReportBuilderPreviewResponse(payload) && !isPriceListComparisonResponse(payload)) return null;
  const executionId = payload.execution_id;
  return typeof executionId === "string" && executionId.trim() !== "" ? executionId : null;
}

/** Document availability belongs to the immutable execution, never the live report. */
export function reportDocumentAvailable(payload: unknown): boolean {
  return isReportBuilderPreviewResponse(payload)
    && payload.document_available === true;
}

export function isSQLReportExecutionResponse(value: unknown): value is SQLReportExecutionResponse {
  if (!value || typeof value !== "object") return false;
  const candidate = value as Partial<SQLReportExecutionResponse>;
  return Array.isArray(candidate.columns)
    && candidate.columns.every((column) => typeof column === "string")
    && Array.isArray(candidate.rows)
    && candidate.rows.every((row) => row != null && typeof row === "object" && !Array.isArray(row))
    && typeof candidate.row_count === "number";
}

export function isPriceListComparisonResponse(value: unknown): value is PriceListComparisonResponse {
  if (!value || typeof value !== "object") return false;
  const candidate = value as Partial<PriceListComparisonResponse>;
  return candidate.report?.code === PRICE_LIST_COMPARISON_CODE
    && candidate.supplier != null
    && candidate.list_a != null
    && candidate.list_b != null
    && candidate.summary != null
    && Array.isArray(candidate.items);
}
